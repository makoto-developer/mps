/**
 * Prisma Schema Generator
 * ASTからPrismaスキーマを生成
 */

import {
  Application,
  Model,
  Field,
  Relationship,
  FieldType,
  FieldConstraint,
  RelationType,
} from '../ast/types';

export class PrismaGenerator {
  generate(app: Application): string {
    const lines: string[] = [];

    // Header
    lines.push('// Generated by Drawing App DSL');
    lines.push('// Do not edit manually');
    lines.push('');

    // Generator client
    lines.push('generator client {');
    lines.push('  provider = "prisma-client-js"');
    lines.push('}');
    lines.push('');

    // Datasource
    lines.push('datasource db {');
    lines.push(`  provider = "${app.database.toLowerCase()}"`);
    lines.push('  url      = env("DATABASE_URL")');
    lines.push('}');
    lines.push('');

    // Enums
    const enums = this.extractEnums(app.models);
    for (const [name, values] of enums) {
      lines.push(`enum ${name} {`);
      for (const value of values) {
        lines.push(`  ${value}`);
      }
      lines.push('}');
      lines.push('');
    }

    // Models
    for (const model of app.models) {
      lines.push(...this.generateModel(model, app.models));
      lines.push('');
    }

    return lines.join('\n');
  }

  private extractEnums(models: Model[]): Map<string, string[]> {
    const enums = new Map<string, string[]>();

    for (const model of models) {
      for (const field of model.fields) {
        if (typeof field.fieldType === 'object' && 'Enum' in field.fieldType) {
          const enumName = `${model.name}${this.capitalize(field.name)}`;
          enums.set(enumName, field.fieldType.Enum);
        }
      }
    }

    return enums;
  }

  private generateModel(model: Model, allModels: Model[]): string[] {
    const lines: string[] = [];

    lines.push(`model ${model.name} {`);

    // Fields
    for (const field of model.fields) {
      lines.push(`  ${this.generateField(field, model)}`);
    }

    // Relationships
    for (const rel of model.relationships) {
      lines.push(`  ${this.generateRelationship(rel, model, allModels)}`);
    }

    lines.push('}');

    return lines;
  }

  private generateField(field: Field, model: Model): string {
    const parts: string[] = [];

    // Field name
    parts.push(field.name);

    // Field type
    const prismaType = this.mapFieldType(field.fieldType, model, field.name);
    parts.push(prismaType);

    // Constraints
    const constraints = this.generateConstraints(field.constraints);
    if (constraints) {
      parts.push(constraints);
    }

    return parts.join(' ');
  }

  private mapFieldType(fieldType: FieldType, model: Model, fieldName: string): string {
    if (typeof fieldType === 'string') {
      const typeMap: Record<string, string> = {
        'String': 'String',
        'Integer': 'Int',
        'Boolean': 'Boolean',
        'DateTime': 'DateTime',
        'UUID': 'String',
        'JSON': 'Json',
        'Float': 'Float',
        'Hash': 'String',
      };
      return typeMap[fieldType] || 'String';
    } else if ('Enum' in fieldType) {
      return `${model.name}${this.capitalize(fieldName)}`;
    }

    return 'String';
  }

  private generateConstraints(constraints: FieldConstraint[]): string {
    const parts: string[] = [];

    for (const constraint of constraints) {
      switch (constraint.type) {
        case 'primary':
          parts.push('@id');
          break;
        case 'auto':
          if (parts.includes('@id')) {
            parts.push('@default(uuid())');
          } else {
            parts.push('@default(now())');
          }
          break;
        case 'unique':
          parts.push('@unique');
          break;
        case 'default':
          if (constraint.value !== undefined) {
            if (typeof constraint.value === 'string') {
              parts.push(`@default("${constraint.value}")`);
            } else if (typeof constraint.value === 'boolean') {
              parts.push(`@default(${constraint.value})`);
            } else {
              parts.push(`@default(${constraint.value})`);
            }
          }
          break;
      }
    }

    return parts.join(' ');
  }

  private generateRelationship(rel: Relationship, model: Model, allModels: Model[]): string {
    const parts: string[] = [];

    // Relationship name
    parts.push(rel.name);

    // Target model
    let targetType = rel.targetModel;
    if (rel.isArray) {
      targetType += '[]';
    }
    if (rel.isOptional) {
      targetType += '?';
    }
    parts.push(targetType);

    // Relation directive
    const relationParts: string[] = [];

    // Add relation name
    relationParts.push(`"${model.name}${rel.name}"`);

    // Add fields and references for ManyToOne relationships
    if (rel.relationType === 'ManyToOne') {
      const foreignKeyName = `${rel.name}Id`;
      relationParts.push(`fields: [${foreignKeyName}]`);
      relationParts.push(`references: [id]`);
    }

    if (relationParts.length > 0) {
      parts.push(`@relation(${relationParts.join(', ')})`);
    }

    // Add foreign key field for ManyToOne
    if (rel.relationType === 'ManyToOne') {
      const foreignKeyName = `${rel.name}Id`;
      return `${parts.join(' ')}\n  ${foreignKeyName} String`;
    }

    return parts.join(' ');
  }

  private capitalize(str: string): string {
    return str.charAt(0).toUpperCase() + str.slice(1);
  }
}
